import { readFile } from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import tailwindcss from '@tailwindcss/postcss';

export const GENERATED_RELATIVE_PATH = 'lib/pdf/print-stylesheet.generated.ts';

/** Compiles app/globals.css exactly like Next does (Tailwind v4 auto source detection from the project root). */
export async function compilePrintStylesheet(rootDir: string): Promise<string> {
  // Virtual entry so we never scan our own output (feedback loop) and no OS-specific absolute paths are needed.
  const entry = `@import "./app/globals.css";\n@source not "./${GENERATED_RELATIVE_PATH}";\n`;
  const result = await postcss([tailwindcss({ optimize: { minify: true } })]).process(entry, {
    from: path.join(rootDir, '__print-entry.css'),
  });
  return result.css;
}

export function renderGeneratedModule(css: string): string {
  return (
    `// @generated by scripts/build-print-css.ts — DO NOT EDIT. Regenerate with: pnpm print-css:build\n` +
    `export const PRINT_STYLESHEET: string = ${JSON.stringify(css)};\n`
  );
}

export async function readCommitted(rootDir: string): Promise<string> {
  return readFile(path.join(rootDir, GENERATED_RELATIVE_PATH), 'utf8');
}
